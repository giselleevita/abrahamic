import { expect, test } from '@playwright/test'

async function openComparison(page: import('@playwright/test').Page) {
  await page.goto('/')
  await page.getByRole('link', { name: 'Explore the perspectives' }).click()
  await expect(page.getByRole('heading', { name: 'Each tradition’s perspective' })).toBeVisible()
}

test('discovery, evidence, reading preferences and saves form one continuous flow', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (e) => errors.push(e.message))
  await openComparison(page)
  await page.getByRole('button', { name: /^Save / }).click()
  const citation = page.getByRole('region', { name: 'Supporting passages' }).getByRole('link').first()
  const href = await citation.getAttribute('href')
  await citation.click()
  await expect(page).toHaveURL(new RegExp(`${href!.split('#')[1]}$`))
  await expect(page.locator(`#${href!.split('#')[1]}`)).toBeVisible()
  await page.getByLabel('Text size', { exact: true }).first().selectOption('24')
  await page.getByLabel('Line spacing', { exact: true }).first().selectOption('spacious')
  await page.locator(`#${href!.split('#')[1]}`).getByRole('button', { name: /^Save / }).click()
  await page.reload()
  await expect(page.getByLabel('Text size', { exact: true }).first()).toHaveValue('24')
  await page.goto('/saved')
  await expect(page.getByRole('list', { name: 'Saved items' }).getByRole('listitem')).toHaveCount(2)
  await page.getByRole('button', { name: 'Clear saved list' }).click()
  await expect(page.getByText('Your collection starts here')).toBeVisible()
  expect(errors).toEqual([])
})

