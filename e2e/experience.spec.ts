test('effects preference persists and the system preference takes precedence', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/')
  await page.getByRole('checkbox', { name: 'Reduce effects' }).check()
  await expect(page.locator('html')).toHaveAttribute('data-reduce-effects', 'true')
  await page.reload()
  await expect(page.getByRole('checkbox', { name: 'Reduce effects' })).toBeChecked()
  await expect(page.locator('.story-scene img').first()).toHaveCSS('transform', 'none')
  await page.getByRole('checkbox', { name: 'Reduce effects' }).uncheck()
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(page.locator('html')).toHaveAttribute('data-reduce-effects', 'true')
})

test('reading and failed saves remain clear when device storage is unavailable', async ({ page }) => {
  await page.addInitScript(() => Object.defineProperty(window, 'localStorage', { get() { throw new Error('Storage unavailable') } }))
  await openComparison(page)
  await page.getByRole('button', { name: /^Save / }).click()
  await expect(page.getByText('Could not save. Device storage is unavailable.')).toBeVisible()
  await page.getByRole('region', { name: 'Supporting passages' }).getByRole('link').first().click()
  await page.getByLabel('Text size', { exact: true }).first().selectOption('24')
  await expect(page.getByLabel('Text size', { exact: true }).first()).toHaveValue('24')
  await expect(page.getByText('Preferences apply for this visit. Device storage is unavailable.').first()).toBeVisible()
})

